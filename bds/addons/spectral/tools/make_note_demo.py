#!/usr/bin/env python3
"""The built-in note song (src/songs/notes_demo.ts): a short piece written for the sampler (an original, no one's music), with
what a tick-bound player cannot do — sixteenths at 96 bpm (156.25 ms, never on the tick), a chord rolled 12 ms a note, a
grace note 20 ms before its beat — so that placing notes inside the tick can be heard and measured.
  python3 tools/make_note_demo.py [--mid out.mid]"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
UNIT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import notes as N

BPM = 96
Q = 60000 / BPM            # a quarter, ms
E, S = Q / 2, Q / 4
NAMES = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}


def k(name):
    """'C4' -> 60, 'F#3' -> 54"""
    pc = NAMES[name[0]] + (1 if '#' in name else -1 if name[1] == 'b' else 0)
    return 12 * (int(name[-1]) + 1) + pc


def piece():
    out = []                                     # (start ms, length ms, key, velocity, program)
    def n(t, d, name, v):
        out.append((t, d, k(name), v, 0))
    bar = 4 * Q
    lh = [['C3', 'G3', 'E4', 'G3'], ['A2', 'E3', 'C4', 'E3'], ['F2', 'C3', 'A3', 'C3'], ['G2', 'D3', 'B3', 'D3'],
          ['E2', 'G3', 'C4', 'G3'], None, ['G2', 'F3', 'B3', 'D4'], None]
    for b, pat in enumerate(lh):
        if pat:
            for i in range(8):
                n(b * bar + i * E, E * 1.6, pat[i % 4], 62 + (8 if i % 4 == 0 else 0))
    n(5 * bar, bar, 'F2', 70); n(5 * bar, bar, 'C3', 64); n(5 * bar, bar, 'A3', 64)
    # the right hand
    mel = [(0, 0, Q, 'E5', 88), (0, Q, E, 'D5', 80), (0, Q + E, E, 'C5', 80), (0, 2 * Q, 2 * Q, 'G5', 92),
           (1, 0, 1.5 * Q, 'A5', 90), (1, 1.5 * Q, E, 'G5', 80), (1, 2 * Q, 2 * Q, 'E5', 86),
           (2, 0, Q, 'F5', 86), (2, Q, Q, 'E5', 80), (2, 2 * Q, Q, 'D5', 80), (2, 3 * Q, Q, 'C5', 78),
           (3, 0, 2 * Q, 'D5', 86)]
    for b, t, d, name, v in mel:
        n(b * bar + t, d, name, v)
    for i, name in enumerate(['B4', 'C5', 'D5', 'E5', 'F5', 'G5', 'A5', 'B5']):       # a run of sixteenths
        n(3 * bar + 2 * Q + i * S, S * 1.2, name, 76 + i * 2)
    for i, name in enumerate(['C6', 'G5', 'E5', 'C5']):
        n(4 * bar + i * Q, Q * 0.9, name, 90 - i * 4)
    n(4 * bar + 2 * Q - 20, 25, 'D5', 60)        # a grace note 20 ms before its beat
    for i, name in enumerate(['A5', 'F5', 'C5', 'A4']):
        n(5 * bar + i * Q, Q * 0.95, name, 84 - i * 3)
    for beat in range(4):                         # sixteenths over the dominant
        for i, name in enumerate(['B4', 'D5', 'F5', 'G5']):
            n(6 * bar + beat * Q + i * S, S * 1.1, name, 70 + (10 if i == 0 else 0))
    for i, name in enumerate(['C2', 'C3', 'G3', 'C4', 'E4', 'G4', 'C5', 'E5']):      # the last chord rolled, 12 ms a note
        n(7 * bar + i * 12, bar + 400, name, 96 - i * 2)
    out.sort(key=lambda x: (x[0], x[2]))
    return out


def band():
    """a few bars for the General MIDI families (an original): strings holding chords (the relay carries them past their samples),
    a pizzicato bass, a flute tune, a vibraphone, a drum kit on channel 10 (kick, snare, hats, a crash)"""
    out = []
    def n(t, d, name, v, prog):
        out.append((t, d, k(name), v, prog))
    bar = 4 * Q
    chords = [['C3', 'G3', 'E4'], ['A2', 'E3', 'C4'], ['F2', 'C3', 'A3'], ['G2', 'D3', 'B3']]
    for b, ch in enumerate(chords):
        for name in ch:
            n(b * bar, bar * 0.98, name, 70, 48)                 # string ensemble
        for i, name in enumerate([ch[0], ch[0], ch[1], ch[0]]):
            n(b * bar + i * Q, Q * 0.6, name.replace('2', '1').replace('3', '2'), 90, 32)   # bass an octave down
        n(b * bar + 2 * Q, Q * 0.5, ch[2].replace('4', '5').replace('3', '5'), 70, 11)       # vibraphone
    tune = [('E5', 0, Q), ('G5', Q, Q), ('A5', 2 * Q, E), ('G5', 2 * Q + E, E), ('E5', 3 * Q, Q), ('C5', 4 * Q, 2 * Q), ('D5', 6 * Q, 2 * Q),
            ('F5', 8 * Q, Q), ('E5', 9 * Q, Q), ('D5', 10 * Q, Q), ('C5', 11 * Q, Q), ('B4', 12 * Q, 2 * Q), ('D5', 14 * Q, 2 * Q)]
    for name, t, d in tune:
        n(t, d * 0.95, name, 92, 73)                              # flute
    for b in range(4):
        for i in range(8):
            out.append((b * bar + i * E, 40, 42, 70 + (10 if i % 2 == 0 else 0), 128))   # closed hi-hat
        out.append((b * bar, 80, 36, 110, 128)); out.append((b * bar + 2 * Q, 80, 36, 100, 128))   # kick
        out.append((b * bar + Q, 80, 38, 100, 128)); out.append((b * bar + 3 * Q, 80, 38, 105, 128))   # snare
    out.append((0, 400, 49, 100, 128))                            # crash
    out.sort(key=lambda x: (x[0], x[2]))
    return out


def main():
    band_song = N.encode(band(), 'band_demo', 'Band (sampler demo)', 'Spectral Player')
    open(os.path.join(UNIT, 'src', 'songs', 'band_demo.ts'), 'w').write(
        '// generated by tools/make_note_demo.py — an original piece for the General MIDI families (do not edit)\n'
        f'export default {json.dumps(band_song, separators=(",", ":"))};\n')
    notes = piece()
    song = N.encode(notes, 'piano_demo', 'Piano étude (sampler demo)', 'Spectral Player')
    ts = ('// generated by tools/make_note_demo.py — an original piece for the sampler (do not edit)\n'
          f'export default {json.dumps(song, separators=(",", ":"))};\n')
    open(os.path.join(UNIT, 'src', 'songs', 'notes_demo.ts'), 'w').write(ts)
    if '--mid' in sys.argv:
        import mido
        mid = mido.MidiFile(ticks_per_beat=960); tr = mido.MidiTrack(); mid.tracks.append(tr)
        tr.append(mido.MetaMessage('set_tempo', tempo=int(Q * 1000)))
        ev = []
        for s, d, key, v, p in notes:
            ev.append((s, 1, key, v)); ev.append((s + d, 0, key, 0))
        ev.sort()
        last = 0
        for t, on, key, v in ev:
            tick = int(round(t / Q * 960))
            tr.append(mido.Message('note_on' if on else 'note_off', note=key, velocity=v, time=tick - last)); last = tick
        mid.save(sys.argv[sys.argv.index('--mid') + 1])
    print(json.dumps({'notes': len(notes), 'seconds': song['meta']['seconds'], 'bytes': len(song['data']) * 3 // 4}))


if __name__ == '__main__':
    main()
